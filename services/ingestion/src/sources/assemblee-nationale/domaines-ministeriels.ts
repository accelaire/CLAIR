/** Clé de comparaison d'un intitulé : sans la précision finale entre parenthèses, normalisé. */
export function cleIntitule(intitule: string): string {
  return normaliserNom(intitule.replace(/\s*\([^)]*\)\s*$/, ''));
}

/** Intitulé normalisé → domaine. Un intitulé rangé dans deux domaines est une erreur de la table. */
export function indexDomaines(table: Record<string, readonly string[]> = INTITULES): Map<string, CleDomaine> {
  const index = new Map<string, CleDomaine>();
  for (const [domaine, intitules] of Object.entries(table) as [CleDomaine, readonly string[]][]) {
    for (const intitule of intitules) {
      const cle = cleIntitule(intitule);
      const deja = index.get(cle);
      if (deja && deja !== domaine) throw new Error(`« ${intitule} » rangé en ${deja} et en ${domaine}`);
      index.set(cle, domaine);
    }
  }
  return index;
}

const INDEX = indexDomaines();

/** Le domaine d'un portefeuille, d'après son intitulé court ; null s'il n'est pas dans la table. */
export function domaineDuPortefeuille(intituleCourt: string | null, intitule: string): CleDomaine | null {
  return INDEX.get(cleIntitule(intituleCourt ?? intitule)) ?? null;
}
