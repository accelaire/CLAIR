// La source ne classe pas les portefeuilles : un gouvernement y est une liste
// de 30 à 70 postes rangés par rang protocolaire, illisible d'un coup d'œil.
// Cette table range chaque intitulé court de l'AMO30 (347 distincts depuis
// 2007) dans un domaine, pour présenter un gouvernement par grands secteurs et
// comparer les gouvernements entre eux.
//
// RÈGLE : le premier thème nommé décide (« Travail, santé et solidarités » →
// travail ; « Ville, jeunesse et sports » → territoires). Deux exceptions,
// parce que le premier mot y trompe sur le cœur du ministère : « Affaires
// sociales et santé » (2012-2017) et « Solidarités et santé » (2017-2022) sont
// les ministères de la Santé de leur époque, rangés en santé.
//
// Les intitulés sont comparés normalisés (casse, accents, ponctuation), sans
// la précision entre parenthèses que l'AN ajoute pour distinguer deux organes
// de même nom (« Fonction publique (II) », « Solidarités et santé (M. Taquet) »).
// Un intitulé absent de la table laisse le poste sans domaine : la synchro
// l'écrit quand même, et le contrôle `postes_sans_domaine` le signale pour
// qu'on l'ajoute ici, sans bloquer la nuit d'un remaniement.
// =============================================================================

